// Original beginner Japanese: ruby also provides the complete kana reading.
const sentence = (scenarioId, index, [ruby, meaningKo, cueKo]) => {
  const text = ruby.map((part) => typeof part === 'string' ? part : part[0]).join('');
  return {
    id: `ja:${scenarioId}:${index + 1}`,
    text,
    meaningKo,
    cueKo,
    audioText: text,
    ruby,
    kana: ruby.map((part) => typeof part === 'string' ? part : part[1]).join(''),
  };
};

const scenario = (id, titleKo, image, lines) => ({
  id,
  titleKo,
  image: `/images/${image}.svg`,
  sentences: lines.map((line, index) => sentence(id, index, line)),
});

